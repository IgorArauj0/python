#variaveis
idade = 30
nome = "João"

print(f"Olá, meu nome é {nome} e eu tenho {idade} anos.")

#Podemos verificar o tipo de dado de uma variável usando a função type()
print(type(idade))  # <class 'int'>
print(type(nome))   # <class 'str'>

#As variaiveis diferenciam letras maiusculas de minusculas
i = 10
I = 20
print(i)  # 10
print(I)  # 20